create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text not null,
  role text not null default 'vendedor' check (role in ('admin', 'vendedor')),
  created_at timestamptz not null default now()
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  barcode text not null unique,
  name text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  total numeric(12,2) not null default 0,
  date timestamptz not null default now(),
  user_id bigint references public.users(id) on delete set null
);
create table if not exists public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  product_id bigint not null references public.products(id),
  quantity integer not null check (quantity > 0),
  price numeric(12,2) not null check (price >= 0)
);
create index if not exists sale_items_sale_id_idx on public.sale_items(sale_id);
create index if not exists sales_date_idx on public.sales(date desc);

alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.sales enable row level security;
alter table public.sale_items enable row level security;

create or replace function public.create_sale(p_user_id bigint, p_items jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare item jsonb; product_row public.products%rowtype; sale_id bigint; total numeric(12,2) := 0; qty integer; current_price numeric(12,2);
begin
  if jsonb_array_length(p_items) = 0 then raise exception 'La venta no contiene productos'; end if;
  for item in select * from jsonb_array_elements(p_items) loop
    qty := (item->>'qty')::integer;
    select * into product_row from public.products where id = (item->>'id')::bigint for update;
    if not found then raise exception 'Producto no encontrado'; end if;
    if product_row.stock < qty then raise exception 'Stock insuficiente para %', product_row.name; end if;
    total := total + product_row.price * qty;
  end loop;
  insert into public.sales(total, user_id) values (total, p_user_id) returning id into sale_id;
  for item in select * from jsonb_array_elements(p_items) loop
    select price into current_price from public.products where id = (item->>'id')::bigint;
    qty := (item->>'qty')::integer;
    insert into public.sale_items(sale_id, product_id, quantity, price) values (sale_id, (item->>'id')::bigint, qty, current_price);
    update public.products set stock = stock - qty, updated_at = now() where id = (item->>'id')::bigint;
  end loop;
  return jsonb_build_object('id', sale_id, 'total', total);
end; $$;

create or replace function public.delete_sale(p_sale_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.products p set stock = p.stock + si.quantity, updated_at = now()
  from public.sale_items si where si.sale_id = p_sale_id and p.id = si.product_id;
  delete from public.sales where id = p_sale_id;
end; $$;

create or replace function public.repair_sequences()
returns void language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('public.users','id'), coalesce((select max(id) from public.users), 1));
  perform setval(pg_get_serial_sequence('public.products','id'), coalesce((select max(id) from public.products), 1));
  perform setval(pg_get_serial_sequence('public.sales','id'), coalesce((select max(id) from public.sales), 1));
  perform setval(pg_get_serial_sequence('public.sale_items','id'), coalesce((select max(id) from public.sale_items), 1));
end; $$;

grant usage on schema public to service_role;
grant all on public.users, public.products, public.sales, public.sale_items to service_role;
grant execute on function public.create_sale(bigint,jsonb), public.delete_sale(bigint), public.repair_sequences() to service_role;
