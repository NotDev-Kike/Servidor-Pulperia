create or replace function public.create_sale_v2(
  p_user_id bigint, p_customer_id bigint, p_items jsonb, p_discount numeric default 0,
  p_payment_method text default 'efectivo', p_amount_paid numeric default 0, p_notes text default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare item jsonb; product_row public.products%rowtype; sale_id bigint; subtotal numeric(12,2):=0; tax numeric(12,2):=0; total numeric(12,2); qty integer; line_total numeric(12,2); paid numeric(12,2):=coalesce(p_amount_paid,0);
begin
  if jsonb_array_length(p_items)=0 then raise exception 'La venta no contiene productos'; end if;
  for item in select * from jsonb_array_elements(p_items) loop
    qty:=(item->>'qty')::integer; select * into product_row from public.products where id=(item->>'id')::bigint and active=true for update;
    if not found then raise exception 'Producto no encontrado'; end if;
    if product_row.stock < qty then raise exception 'Stock insuficiente para %',product_row.name; end if;
    line_total:=product_row.price*qty; subtotal:=subtotal+line_total; tax:=tax+round(line_total*product_row.tax_rate/100,2);
  end loop;
  total:=greatest(0,subtotal+tax-coalesce(p_discount,0));
  if p_payment_method='credito' and p_customer_id is null then raise exception 'Selecciona un cliente para vender al crédito'; end if;
  if p_payment_method='credito' then paid:=0; end if;
  insert into public.sales(total,date,user_id,customer_id,subtotal,discount,tax,payment_method,payment_status,amount_paid,change_given,notes) values(total,now(),p_user_id,p_customer_id,subtotal,coalesce(p_discount,0),tax,p_payment_method,case when p_payment_method='credito' then 'pendiente' else 'pagada' end,paid,greatest(0,paid-total),p_notes) returning id into sale_id;
  for item in select * from jsonb_array_elements(p_items) loop
    qty:=(item->>'qty')::integer; select * into product_row from public.products where id=(item->>'id')::bigint;
    insert into public.sale_items(sale_id,product_id,quantity,price) values(sale_id,product_row.id,qty,product_row.price);
    update public.products set stock=stock-qty,updated_at=now() where id=product_row.id;
  end loop;
  if p_payment_method='credito' then update public.customers set balance=balance+total where id=p_customer_id; end if;
  return jsonb_build_object('id',sale_id,'subtotal',subtotal,'tax',tax,'total',total,'change_given',greatest(0,paid-total));
end; $$;

create or replace function public.create_purchase(p_user_id bigint,p_supplier_id bigint,p_items jsonb,p_payment_method text default 'efectivo',p_notes text default null) returns jsonb language plpgsql security definer set search_path=public as $$
declare item jsonb; product_row public.products%rowtype; purchase_id bigint; subtotal numeric(12,2):=0; total numeric(12,2); qty integer; cost numeric(12,2);
begin
  if jsonb_array_length(p_items)=0 then raise exception 'La compra no contiene productos'; end if;
  for item in select * from jsonb_array_elements(p_items) loop qty:=(item->>'qty')::integer;cost:=(item->>'cost_price')::numeric;subtotal:=subtotal+(qty*cost);end loop;
  total:=subtotal;
  insert into public.purchases(supplier_id,date,subtotal,total,payment_method,notes,user_id) values(p_supplier_id,now(),subtotal,total,p_payment_method,p_notes,p_user_id) returning id into purchase_id;
  for item in select * from jsonb_array_elements(p_items) loop qty:=(item->>'qty')::integer;cost:=(item->>'cost_price')::numeric;select * into product_row from public.products where id=(item->>'id')::bigint for update;if not found then raise exception 'Producto no encontrado';end if;insert into public.purchase_items(purchase_id,product_id,quantity,cost_price,tax_rate) values(purchase_id,product_row.id,qty,cost,product_row.tax_rate);update public.products set stock=stock+qty,cost_price=cost,updated_at=now() where id=product_row.id;end loop;
  return jsonb_build_object('id',purchase_id,'total',total);
end; $$;
grant execute on function public.create_sale_v2(bigint,bigint,jsonb,numeric,text,numeric,text),public.create_purchase(bigint,bigint,jsonb,text,text) to service_role;

