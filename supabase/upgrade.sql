create or replace function public.create_sale_v2(
  p_user_id bigint, p_customer_id bigint, p_items jsonb, p_discount numeric default 0,
  p_payment_method text default 'efectivo', p_amount_paid numeric default 0, p_notes text default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare item jsonb; product_row public.products%rowtype; customer_row public.customers%rowtype; sale_id bigint; subtotal numeric(12,2):=0; total numeric(12,2); qty integer; line_total numeric(12,2); paid numeric(12,2):=coalesce(p_amount_paid,0);
begin
  if jsonb_array_length(p_items)=0 then raise exception 'La venta no contiene productos'; end if;
  if p_payment_method not in ('efectivo','transferencia','credito') then raise exception 'Método de pago no permitido'; end if;
  if p_payment_method='credito' then
    if p_customer_id is null then raise exception 'Selecciona un cliente autorizado para vender al crédito'; end if;
    select * into customer_row from public.customers where id=p_customer_id and active=true for update;
    if not found or not customer_row.credit_enabled then raise exception 'El cliente no tiene crédito autorizado'; end if;
  end if;
  for item in select * from jsonb_array_elements(p_items) loop
    qty:=(item->>'qty')::integer; select * into product_row from public.products where id=(item->>'id')::bigint and active=true for update;
    if not found then raise exception 'Producto no encontrado'; end if;
    if product_row.stock < qty then raise exception 'Stock insuficiente para %',product_row.name; end if;
    line_total:=product_row.price*qty; subtotal:=subtotal+line_total;
  end loop;
  total:=subtotal; if p_payment_method='credito' then paid:=0; end if;
  insert into public.sales(total,date,user_id,customer_id,subtotal,discount,tax,payment_method,payment_status,amount_paid,change_given,notes,transfer_status)
  values(total,now(),p_user_id,p_customer_id,subtotal,0,0,p_payment_method,case when p_payment_method='credito' then 'pendiente' else 'pagada' end,paid,greatest(0,paid-total),p_notes,case when p_payment_method='transferencia' then 'pendiente' else 'no_aplica' end) returning id into sale_id;
  for item in select * from jsonb_array_elements(p_items) loop
    qty:=(item->>'qty')::integer; select * into product_row from public.products where id=(item->>'id')::bigint;
    insert into public.sale_items(sale_id,product_id,quantity,price) values(sale_id,product_row.id,qty,product_row.price);
    update public.products set stock=stock-qty,updated_at=now() where id=product_row.id;
  end loop;
  if p_payment_method='credito' then update public.customers set balance=balance+total where id=p_customer_id; end if;
  return jsonb_build_object('id',sale_id,'subtotal',subtotal,'tax',0,'discount',0,'total',total,'change_given',greatest(0,paid-total),'payment_status',case when p_payment_method='transferencia' then 'pendiente' else 'pagada' end);
end; $$;
